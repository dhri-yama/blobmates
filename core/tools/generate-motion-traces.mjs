// Writes core/spec/motion-traces.json: what the JS runtime does, frame by frame, in a fake world with a fake clock and
// seeded random numbers (see motion-driver.mjs). Other ports replay the same scripts and must match.
//   node core/tools/generate-motion-traces.mjs          write the file
//   node core/tools/generate-motion-traces.mjs --check  exit 1 if the file is out of date (used by the JS tests)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { SCENARIOS, runScenario } from './motion-driver.mjs';

const file = new URL('../spec/motion-traces.json', import.meta.url);
const out = {
  note: 'GENERATED by core/tools/generate-motion-traces.mjs. Do not edit. See core/spec/MOTION.md and core/spec/README.md.',
  parts: { sha256: createHash('sha256').update(readFileSync(new URL('../assets/parts.json', import.meta.url))).digest('hex') },
  rules: 'Time starts at 1000 ms. Frame i is at 1000 + the sum of gaps 0..i, gap = 70 ms when i % 37 == 36, else 1000/60 ms. Per frame: scripted events, then due timers (in due-time order), then the frame. Math.random = mulberry32(randomSeed) / 2^32.',
  startMs: 1000,
  frameColumns: ['x', 'y', 'rotationDeg|null', 'scaleX|null', 'scaleY|null', 'pictureHash'],
  scenarios: SCENARIOS.map((script) => ({ ...script, trace: runScenario(script) })),
};
const text = JSON.stringify(out) + '\n';

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(file, 'utf8'); } catch { /* missing */ }
  if (current !== text) { console.error('core/spec/motion-traces.json is out of date: run node core/tools/generate-motion-traces.mjs and review the diff'); process.exit(1); }
  console.log(`motion traces up to date (${out.scenarios.length} scenarios)`);
} else {
  writeFileSync(file, text);
  console.log('traces:', out.scenarios.map((s) => `${s.name} (${s.trace.length} frames)`).join(', '));
}
